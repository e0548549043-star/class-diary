/** מחזיר את נושא השיעור ה־n (מתחיל ב־0) במקצוע מסוים לכיתה בשכבה מסוימת */
export function topicFor(subject: string, grade: number, n: number): string {
  const pick = (list: string[]) => list[Math.min(n, list.length - 1)]!;
  const cycle = (list: string[]) => list[n % list.length]!;
  switch (subject) {
    case "חומש":
      return `ספר ${CHUMASH_BOOKS[grade] ?? "שמות"} פרק ${Math.floor(n / 2) + 1}`;
    case "נביא":
      return `ספר ${NAVI_BOOKS[grade] ?? "יהושע"} פרק ${Math.floor(n / 2) + 1}`;
    case "הלכה":
      return pick(HALACHA);
    case "תולדות עם ישראל":
      return pick(HISTORY);
    case "לשון":
      return pick(LASHON);
    case "הבעה":
      return cycle(HABAA);
    case "מתמטיקה":
      return pick(MATH[grade] ?? MATH[7]!);
    case "אנגלית":
      return pick(ENGLISH);
    case "מדעים":
      return pick(SCIENCE);
    case "גאוגרפיה":
      return pick(GEOGRAPHY);
    case "מחשבים":
      return cycle(COMPUTERS);
    case "חינוך":
      return pick(CHINUCH);
    default:
      return "שיעור";
  }
}

